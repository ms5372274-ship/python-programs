# Python Variables – Complete Q&A

# Q1. Variable kya hota hai?
# Answer: Variable ek naam hota hai jiske through program mein kisi value ko store ya refer kiya jata hai.

# Q2. Python mein variable kaise create karte hain?
# Answer: Assignment operator = ka use karke variable create kiya jata hai.

# Q3. Variable ka use kyon kiya jata hai?
# Answer: Data ko store karne aur program mein baad mein use karne ke liye variable ka use kiya jata hai.

# Q4. Python mein variable declare karne ki kya syntax hai?
# Answer: Variable name ke baad = aur uske baad value likhi jati hai.

# Q5. Python mein variable ka data type kaise check karte hain?
# Answer: type() function se variable ka data type check kar sakte hain.

# Q6. type() function kya hai?
# Answer: type() Python ka built-in function hai jo kisi value ya variable ka data type batata hai.

# Q7. Python dynamically typed language ka kya meaning hai?
# Answer: Iska meaning hai ki variable ka data type pehle se declare karna zaroori nahi hota. Python value ke according type determine karta hai.

# Q8. Kya Python mein variable banate time data type declare karna zaroori hai?
# Answer: Nahi, Python mein data type explicitly declare karna zaroori nahi hai.

# Q9. Variable ko value kaise assign karte hain?
# Answer: Assignment operator = ki help se variable ko value assign karte hain.

# Q10. Kya ek variable ki value change kar sakte hain?
# Answer: Haan, Python mein variable ki value ko baad mein change kiya ja sakta hai.

# Q11. Variable name ke rules kya hain?
# Answer: Variable name letter ya underscore se start hona chahiye, number se start nahi ho sakta, spaces allowed nahi hain aur Python keywords use nahi kar sakte.

# Q12. Kya variable name number se start ho sakta hai?
# Answer: Nahi, variable name number se start nahi ho sakta.

# Q13. Kya variable name mein space use kar sakte hain?
# Answer: Nahi, variable name mein space allowed nahi hai.

# Q14. Variable name mein underscore _ ka use kaise karte hain?
# Answer: Words ko separate karne ke liye underscore ka use kiya ja sakta hai.

# Q15. Python mein variable names case-sensitive hote hain?
# Answer: Haan, Python case-sensitive hai. Capital aur small letters ko different maana jata hai.

# Q16. Valid aur invalid variable names kya hote hain?
# Answer: Jo variable names Python ke naming rules follow karte hain wo valid hote hain; rules follow na karne wale invalid hote hain.

# Q17. Python mein multiple variables ko ek saath kaise assign karte hain?
# Answer: Multiple variables ko ek statement mein multiple values assign ki ja sakti hain.

# Q18. Ek hi value ko multiple variables mein kaise assign karte hain?
# Answer: Multiple variable names ko ek hi value ke saath assign karke.

# Q19. input() se variable mein value kaise store karte hain?
# Answer: input() function user se data leta hai aur us value ko variable mein store kiya ja sakta hai.

# Q20. input() function se milne wali value ka data type kya hota hai?
# Answer: By default input() function string (str) return karta hai.

# Q21. Input value ko integer variable mein kaise convert karte hain?
# Answer: int() function ki help se input value ko integer mein convert kar sakte hain.

# Q22. String kya hoti hai?
# Answer: String characters ka collection hoti hai, jaise text ya words.

# Q23. Integer kya hota hai?
# Answer: Integer whole numbers hote hain, jaise positive, negative aur zero numbers.

# Q24. Float kya hota hai?
# Answer: Float decimal numbers ko represent karta hai.

# Q25. Boolean kya hota hai?
# Answer: Boolean data type ke sirf do values hoti hain: True aur False.

# Q26. Python mein variable ko delete kaise karte hain?
# Answer: Variable ko delete karne ke liye del keyword ka use kiya jata hai.

# Q27. del keyword kya hai?
# Answer: del Python ka keyword hai jo variable ya kisi object ke reference ko remove karne ke liye use hota hai.

# Q28. Kya Python keywords ko variable name ke roop mein use kar sakte hain?
# Answer: Nahi, Python keywords ko variable names ke roop mein use nahi kar sakte.

# Q29. Variable aur constant mein kya difference hai?
# Answer: Variable ki value change ho sakti hai, jabki constant ki value ko program ke dauran change nahi kiya jana chahiye.

# Q30. Local variable kya hota hai?
# Answer: Jo variable kisi function ya local scope ke andar create hota hai aur mainly wahi accessible hota hai, use local variable kehte hain.

# Q31. Global variable kya hota hai?
# Answer: Jo variable program ke broader/global scope mein define hota hai, use global variable kehte hain.

# Q32. Local aur global variable mein kya difference hai?
# Answer: Local variable ka scope limited hota hai, jabki global variable ka scope program ke broader area mein hota hai.

# Q33. Variable assignment kya hota hai?
# Answer: Kisi variable ko value dene ki process ko variable assignment kehte hain.

# Q34. Python mein memory management kya hota hai?
# Answer: Python automatically objects aur unki memory ko manage karta hai, jisme garbage collection bhi included hai.

# Q35. Kya variable mein different type ki value store kar sakte hain?
# Answer: Haan, Python dynamically typed hone ke karan ek variable ko alag time par different data types ki values assign ki ja sakti hain.

# Q36. Variable aur value mein kya difference hai?
# Answer: Variable ek naam/reference hai, jabki value actual data hota hai jo variable refer karta hai.

# Q37. Assignment operator kya hai?
# Answer: = assignment operator hai, iska use variable ko value assign karne ke liye hota hai.

# Q38. Kya variable name case-sensitive hai?
# Answer: Haan, Python mein uppercase aur lowercase letters ko different maana jata hai.

# Q39. Kya underscore se variable name start kar sakte hain?
# Answer: Haan, Python mein variable name underscore _ se start ho sakta hai.

# Q40. Python variable ki main characteristics kya hain?
# Answer: Python variables dynamically typed hote hain, unka type automatically determine hota hai aur unki value program ke dauran change ki ja sakti hai.











