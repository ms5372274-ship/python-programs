# Q1. What is a Data Type in Python?

# Answer:
# A data type specifies the type of value stored in a variable and determines the operations that can be performed on that value.

# Q2. What are the built-in data types in Python?

# Answer:
# Python provides several built-in data types:

# int
# float
# complex
# bool
# str
# list
# tuple
# set
# dict
# NoneType


# Q3. What is an Integer (int)?

# Answer:
# An integer is a whole number without a decimal or fractional part.


# Q4. What is a Float (float)?

# Answer:
# A float is a number that contains a decimal point.




# Q5. What is a Complex data type?

# Answer:
# A complex number consists of a real part and an imaginary part. Python uses j to represent the imaginary part.


# Q6. What is Boolean (bool) data type?

# Answer:
# Boolean data type represents one of two values: True or False.



# Q7. What is a String (str)?

# Answer:
# A string is a sequence of characters enclosed in single or double quotation marks.



# Q8. What is a List in Python?

# Answer:
# A list is an ordered and mutable collection of elements. It is written using square brackets [ ].



# Q9. What is a Tuple?

# Answer:
# A tuple is an ordered and immutable collection of elements. It is written using parentheses ( ).


# Q10. What is a Set?

# Answer:
# A set is an unordered collection of unique elements. Duplicate elements are automatically removed.



# Q11. What is a Dictionary?

# Answer:
# A dictionary is a mutable collection that stores data in the form of key-value pairs.



# Q12. What is NoneType?

# Answer:
# NoneType represents the absence of a value. The special value used is None.



# Q14. What is a mutable data type?

# Answer:
# A mutable data type is a data type whose contents can be changed after the object is created.

# Examples:
# list, set, dict

# Q15. What is an immutable data type?

# Answer:
# An immutable data type is a data type whose contents cannot be changed after the object is created.

# Examples:
# int, float, complex, bool, str, tuple

# Q16. What is the difference between List and Tuple?
# List	Tuple
# Mutable	Immutable
# Uses [ ]	Uses ( )
# Values can be changed	Values cannot be changed
# Example: [1, 2, 3]	Example: (1, 2, 3)




# Q17. What is the difference between Set and Dictionary?
# Set	Dictionary
# Stores unique values	Stores key-value pairs
# Uses { }	Uses {key: value}
# No key-value structure	Has key-value structure
# Example: {10, 20, 30}	Example: {"age": 21}



