# Q1. What is an if statement in Python?
# Answer: The if statement is used to execute a block of code when a given condition is True.

# Q2. What is an else statement?
# Answer: The else statement executes a block of code when the if condition is False.

# Q3. What is an if-else statement?
# Answer: An if-else statement is used for decision-making. It executes one block when the condition is True and another block when it is False.

# Q4. What is a condition?
# Answer: A condition is an expression that returns either True or False.

# Q5. What are Boolean values?
# Answer: Boolean values are True and False.

# Q6. What is indentation in Python?
# Answer: Indentation is the space at the beginning of a line that defines a block of code.

# Q7. Why is : used after an if condition?
# Answer: The colon indicates the beginning of the code block associated with the if statement.

# Q8. What is the syntax of an if statement?
# Answer:

# if condition:
#     statement

# Q9. What is the syntax of an if-else statement?
# Answer:

# if condition:
#     statement
# else:
#     statement

# Q10. What is elif in Python?
# Answer: elif means "else if" and is used to check another condition when the previous condition is False.

# Q11. What is a nested if statement?
# Answer: A nested if is an if statement written inside another if statement.

# Q12. What happens when the if condition is True?
# Answer: The statements inside the if block are executed.

# Q13. What happens when the if condition is False?
# Answer: If an else block is present, the statements inside the else block are executed.

# Q14. Can an if statement be used without else?
# Answer: Yes, an if statement can be used without an else statement.

# Q15. What are the decision-making statements in Python?
# Answer: The main decision-making statements are if, if-else, if-elif-else, and nested if.



	
















