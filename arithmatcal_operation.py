# Arithmetic Operators in Python

# Arithmetic operators are used to perform mathematical calculations.

# +   Addition
# -   Subtraction
# *   Multiplication
# /   Division
# //  Floor Division
# %   Modulus
# **  Exponentiation

# Example:

# a = 20
# b = 6

# Addition:        a + b = 26
# Subtraction:     a - b = 14
# Multiplication:  a * b = 120
# Division:        a / b = 3.3333
# Floor Division:  a // b = 3
# Modulus:         a % b = 2
# Exponentiation:  a ** b = 64000000





# Q1. What are Arithmetic Operators?
# Answer: Arithmetic Operators are used to perform mathematical calculations in Python.

# Q2. What is the Addition operator?
# Answer: The + operator is used to add two values.

# Q3. What is the Subtraction operator?
# Answer: The - operator is used to subtract one value from another.

# Q4. What is the Multiplication operator?
# Answer: The * operator is used to multiply two values.

# Q5. What is the Division operator?
# Answer: The / operator is used to divide one value by another.

# Q6. What is Floor Division?
# Answer: The // operator performs division and returns the floor value of the result.

# Q7. What is the Modulus operator?
# Answer: The % operator returns the remainder after division.

# Q8. What is the Exponentiation operator?
# Answer: The ** operator is used to calculate the power of a number.

# Q9. What are the main Arithmetic Operators in Python?
# Answer: +, -, *, /, //, %, and **.

# Q10. What is the difference between / and //?
# Answer: / returns the normal division result, while // returns the floor division result.





